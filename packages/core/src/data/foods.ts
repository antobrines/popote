/**
 * Catalogue d'aliments de départ.
 *
 * - Valeurs nutritionnelles : table Ciqual 2020 de l'Anses (voir `ciqual.ts`, fichier généré), pour
 *   100 g de produit TEL QU'ACHETÉ (cru pour viandes, poissons et féculents). Les valeurs `per100`
 *   écrites ci-dessous ne servent que pour les quelques aliments absents de la table (skyr, whey,
 *   mélanges d'épices…) : ce sont alors des moyennes d'étiquettes.
 * - Prix : ESTIMATIONS indicatives (source `estimate`). Elles ne proviennent d'aucun magasin :
 *   elles servent de valeur par défaut tant que l'utilisateur n'a pas relevé ses propres prix.
 */
import type { Aisle, CookingInstruction, Food, FoodCategory, Nutrients, PackageOption } from '../types.js';
import { CIQUAL_VALUES } from './ciqual.js';

/**
 * Version du catalogue : à changer quand des valeurs nutritionnelles évoluent, pour que les
 * programmes déjà enregistrés soient recalculés à la prochaine ouverture.
 */
export const CATALOG_VERSION = 'ciqual-2020-07-07';

type N5 = [kcal: number, protein: number, carbs: number, fat: number, fiber: number];

function n(v: N5): Nutrients {
  return { kcal: v[0], protein: v[1], carbs: v[2], fat: v[3], fiber: v[4] };
}

function pack(label: string, grams: number, price: number, variableWeight = false): PackageOption {
  return { label, grams, price, source: 'estimate', ...(variableWeight ? { variableWeight } : {}) };
}

interface FoodSeed {
  id: string;
  name: string;
  shortName: string;
  category: FoodCategory;
  aisle: Aisle;
  per100: N5;
  portion: [min: number, max: number, step: number];
  packages: PackageOption[];
  keywords: string[];
  off?: string[];
  unit?: 'g' | 'ml';
  piece?: [label: string, plural: string, grams: number];
  cookedYield?: number;
  portable?: boolean;
  noCook?: boolean;
  perishable?: boolean;
  cooking?: CookingInstruction[];
  tags?: string[];
  group?: string;
}

function food(s: FoodSeed): Food {
  const reference = CIQUAL_VALUES[s.id];
  return {
    id: s.id,
    name: s.name,
    shortName: s.shortName,
    category: s.category,
    aisle: s.aisle,
    per100: reference ? { ...reference.per100 } : n(s.per100),
    ciqual: reference ? { code: reference.code, label: reference.label, energyComputed: reference.energyComputed, note: reference.note } : undefined,
    unit: s.unit ?? 'g',
    piece: s.piece ? { label: s.piece[0], plural: s.piece[1], grams: s.piece[2] } : undefined,
    cookedYield: s.cookedYield,
    portable: s.portable ?? false,
    noCook: s.noCook ?? false,
    portion: { min: s.portion[0], max: s.portion[1], step: s.portion[2] },
    cooking: s.cooking,
    perishable: s.perishable ?? true,
    packages: s.packages,
    tags: s.tags ?? [],
    keywords: s.keywords,
    offCategories: s.off ?? [],
    substitutionGroup: s.group,
  };
}

const cook = (mode: CookingInstruction['mode'], minutes: number, text: string): CookingInstruction => ({
  mode,
  minutes,
  text,
});

